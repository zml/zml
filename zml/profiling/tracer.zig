/// Identifies a work handoff, independently of the spans describing it.
/// Pass the same context with the work to its consumer. IDs are generated by
/// this executable's TraceMe recorder; other loaded plugins have separate generators.
/// The public fields also allow importing an existing backend context explicitly.
pub const Context = struct {
    namespace: ContextType,
    id: i64,

    pub fn init(namespace: ContextType) Context {
        return .{ .namespace = namespace, .id = c.zml_traceme_new_activity_id() };
    }
};

/// A span can receive work, schedule work, or do both using distinct contexts.
pub const SpanContext = struct {
    producer: ?Context = null,
    consumer: ?Context = null,
};

pub fn source_to_string(comptime src: std.lang.SourceLocation) [std.fmt.count("{s}:{d}:{d}", .{ src.file, src.line, src.column })]u8 {
    return std.fmt.comptimePrint("{s}:{d}:{d}", .{ src.file, src.line, src.column }).*;
}

/// Like span, with an additional _src=file:line:column metadata field.
/// The caller's metadata must not contain _src; this field is reserved here.
pub fn span_at(comptime src: std.lang.SourceLocation, comptime name: []const u8, metadata: anytype) Span {
    // std.debug.print("coucou {s}:{s}+{}:{s}\n", .{ src.file, src.fn_name, src.line, name });
    const metadata_len = comptime switch (@typeInfo(@TypeOf(metadata))) {
        .void => name.len,
        .@"struct" => computeEncodedNameLen(name, @TypeOf(metadata)),
        else => @compileError("Unsupported metadata."),
    };
    // Allow #_src=value# even when the caller supplies no metadata.
    var buffer: [metadata_len + source_to_string(src).len + 7]u8 = undefined;
    var encoded: std.ArrayList(u8) = .initBuffer(&buffer);
    appendEncodedNameAt(&encoded, .failing, src, name, metadata) catch unreachable;
    return .start(encoded.items);
}

/// Like span_at, with typed producer/consumer correlations. These are encoded
/// as integer _pt/_p and _ct/_c fields; metadata must not contain those keys.
/// An internal _zml_flow marker distinguishes these flows in Perfetto exports.
/// Correlation annotates a handoff; it does not schedule or synchronize work.
pub fn span_at_for(comptime src: std.lang.SourceLocation, comptime name: []const u8, metadata: anytype, context: SpanContext) Span {
    const metadata_len = comptime switch (@typeInfo(@TypeOf(metadata))) {
        .void => name.len,
        .@"struct" => computeEncodedNameLen(name, @TypeOf(metadata)),
        else => @compileError("Unsupported metadata."),
    };
    var buffer: [metadata_len + source_to_string(src).len + 7 + max_context_fields_len]u8 = undefined;
    var encoded: std.ArrayList(u8) = .initBuffer(&buffer);
    appendEncodedNameAtFor(&encoded, .failing, src, name, metadata, context) catch unreachable;
    return .start(encoded.items);
}

const max_context_fields_len = ",_zml_flow=1".len + std.fmt.count(",_pt={d},_p={d},_ct={d},_c={d}", .{
    std.math.minInt(i32), std.math.minInt(i64), std.math.minInt(i32), std.math.minInt(i64),
});

fn appendEncodedNameAtFor(buffer: *std.ArrayList(u8), allocator: std.mem.Allocator, comptime src: std.lang.SourceLocation, name: []const u8, metadata: anytype, context: SpanContext) !void {
    if (@typeInfo(@TypeOf(metadata)) == .@"struct") {
        inline for (.{ "_pt", "_p", "_ct", "_c", "_zml_flow" }) |key| {
            if (@hasField(@TypeOf(metadata), key)) {
                @compileError("span_at_for reserves metadata field '" ++ key ++ "' for its context");
            }
        }
    }
    try appendEncodedNameAt(buffer, allocator, src, name, metadata);
    // Source metadata guarantees one existing #...# section. Extend that section.
    buffer.items.len -= 1;
    if (context.producer) |producer| {
        try buffer.print(allocator, ",_pt={d},_p={d}", .{ @backingInt(producer.namespace), producer.id });
    }
    if (context.consumer) |consumer| {
        try buffer.print(allocator, ",_ct={d},_c={d}", .{ @backingInt(consumer.namespace), consumer.id });
    }
    if (context.producer != null or context.consumer != null) {
        try buffer.appendSlice(allocator, ",_zml_flow=1");
    }
    try buffer.append(allocator, '#');
}

fn appendEncodedNameAt(buffer: *std.ArrayList(u8), allocator: std.mem.Allocator, comptime src: std.lang.SourceLocation, name: []const u8, metadata: anytype) !void {
    switch (@typeInfo(@TypeOf(metadata))) {
        .void => try appendEncodedName(buffer, allocator, name, .{}),
        .@"struct" => {
            if (@hasField(@TypeOf(metadata), "_src")) {
                @compileError("span_at reserves metadata field '_src' for the source location");
            }
            try appendEncodedName(buffer, allocator, name, metadata);
        },
        else => @compileError("Unsupported metadata."),
    }

    // Extend the existing metadata section rather than creating a second one.
    if (buffer.items.len > name.len) {
        buffer.items.len -= 1;
        try buffer.append(allocator, ',');
    } else {
        try buffer.append(allocator, '#');
    }
    const source = comptime source_to_string(src);
    validateMetadataToken(&source);
    try buffer.appendSlice(allocator, "_src=");
    try buffer.appendSlice(allocator, &source);
    try buffer.append(allocator, '#');
}

/// Creates a Span with encoded metadata. The metadata encoded size must be known at compile time.
/// If it's not your case, use `formatSpanName` to generate the span name before and use void for the metadata.
pub fn span(comptime name: []const u8, metadata: anytype) Span {
    switch (@typeInfo(@TypeOf(metadata))) {
        .void => {
            return .start(name);
        },
        .@"struct" => |info| {
            if (info.field_names.len == 0) {
                return .start(name);
            }

            var buffer: [computeEncodedNameLen(name, @TypeOf(metadata))]u8 = undefined;
            var encoded: std.ArrayList(u8) = .initBuffer(&buffer);

            appendEncodedName(&encoded, .failing, name, metadata) catch unreachable;
            return .start(encoded.items);
        },
        else => @compileError("Unsupported metadata."),
    }
}

/// Returns an allocator-owned encoded span name for metadata that cannot be
/// bounded by `span` at comptime. The caller owns the returned slice.
pub fn formatSpanName(allocator: std.mem.Allocator, name: []const u8, metadata: anytype) ![]const u8 {
    switch (@typeInfo(@TypeOf(metadata))) {
        .@"struct" => {
            var encoded: std.ArrayList(u8) = .empty;
            errdefer encoded.deinit(allocator);

            try appendEncodedName(&encoded, allocator, name, metadata);
            return try encoded.toOwnedSlice(allocator);
        },
        else => @compileError("trace metadata must be a struct literal like .{ .step_num = 42 }"),
    }
}

fn appendEncodedName(buffer: *std.ArrayList(u8), allocator: std.mem.Allocator, name: []const u8, metadata: anytype) !void {
    try buffer.appendSlice(allocator, name);

    var field_count: usize = 0;
    try buffer.append(allocator, '#');
    inline for (comptime std.meta.fieldNames(@TypeOf(metadata))) |field_name| {
        if (shouldEncodeField(field_name, @field(metadata, field_name))) {
            if (field_count != 0) {
                try buffer.append(allocator, ',');
            }
            field_count += 1;

            const key = comptime metadataKey(field_name);
            validateMetadataToken(key);
            try buffer.appendSlice(allocator, key);
            try buffer.append(allocator, '=');
            try appendMetadataValue(buffer, allocator, @field(metadata, field_name), field_name);
        }
    }

    // We may not have written any fields because of optional values.
    if (field_count == 0) {
        buffer.items.len = name.len;
    } else {
        try buffer.append(allocator, '#');
    }
}

fn validateMetadataToken(token: []const u8) void {
    if (std.mem.indexOfScalar(u8, token, '#') != null) {
        @panic("trace metadata cannot contain '#'");
    }
}

fn metadataKey(comptime field_name: []const u8) []const u8 {
    return if (comptime std.mem.eql(u8, field_name, "root")) "_r" else field_name;
}

fn computeEncodedNameLen(comptime name: []const u8, comptime Metadata: type) usize {
    switch (@typeInfo(Metadata)) {
        .@"struct" => |info| {
            if (info.field_names.len == 0) return name.len;

            // name#[attrs]#
            var max_len = name.len + 2;
            inline for (
                info.field_names,
                info.field_types,
                info.field_attrs,
            ) |field_name, FieldType, field_attr| {
                const key = comptime metadataKey(field_name);
                validateMetadataToken(key);

                const default: ?FieldType = field_attr.defaultValue(FieldType);
                // [key]=[value],
                max_len += key.len + 2;
                max_len += switch (@typeInfo(FieldType)) {
                    .bool => 1,
                    .int => @max(
                        std.fmt.comptimePrint("{}", .{std.math.minInt(FieldType)}).len,
                        std.fmt.comptimePrint("{}", .{std.math.maxInt(FieldType)}).len,
                    ),
                    .@"enum" => |ty| b: {
                        var max_enum_len: usize = 0;
                        for (ty.field_names) |enum_field_name| {
                            max_enum_len = @max(max_enum_len, enum_field_name.len);
                        }
                        break :b max_enum_len;
                    },
                    .comptime_int => std.fmt.comptimePrint("{}", .{default.?}).len,
                    .comptime_float => std.fmt.comptimePrint("{d}", .{default.?}).len,
                    .enum_literal => @tagName(default.?).len,
                    else => @compileError("trace metadata field '" ++ field_name ++ "' is not statically bounded; use formatspanName"),
                };
            }
            return max_len;
        },
        else => @compileError("trace metadata must be a struct literal like .{ .step_num = 42 }"),
    }
}

fn shouldEncodeField(comptime field_name: []const u8, value: anytype) bool {
    const FieldType = @TypeOf(value);
    return switch (@typeInfo(FieldType)) {
        .optional => value != null,
        .bool => if (comptime std.mem.eql(u8, field_name, "root")) value else true,
        else => true,
    };
}

fn appendMetadataValue(buffer: *std.ArrayList(u8), allocator: std.mem.Allocator, value: anytype, comptime field_name: []const u8) !void {
    const T = @TypeOf(value);
    switch (@typeInfo(T)) {
        .optional => {
            try appendMetadataValue(buffer, allocator, value.?, field_name);
        },
        .bool => {
            if (comptime std.mem.eql(u8, field_name, "root")) {
                try buffer.append(allocator, '1');
            } else {
                try buffer.appendSlice(allocator, if (value) "1" else "0");
            }
        },
        .int, .comptime_int => try buffer.print(allocator, "{}", .{value}),
        .float, .comptime_float => try buffer.print(allocator, "{d}", .{value}),
        .enum_literal => try buffer.appendSlice(allocator, @tagName(value)),
        .@"enum" => try buffer.appendSlice(allocator, @tagName(value)),
        .pointer => |ptr| {
            if (ptr.size == .slice and ptr.child == u8) {
                validateMetadataToken(value);
                try buffer.appendSlice(allocator, value);
                return;
            }

            if (ptr.size == .one) switch (@typeInfo(ptr.child)) {
                .array => |arr| {
                    if (arr.child == u8) {
                        const slice = value[0..];
                        validateMetadataToken(slice);
                        try buffer.appendSlice(allocator, slice);
                        return;
                    }
                },
                else => {},
            };

            @compileError("trace metadata pointers must be []const u8 or string literals");
        },
        .array => |arr| {
            if (arr.child != u8) {
                @compileError("trace metadata arrays must be [N]u8");
            }
            validateMetadataToken(value[0..]);
            try buffer.appendSlice(allocator, value[0..]);
        },
        else => @compileError("unsupported trace metadata type for field '" ++ field_name ++ "'"),
    }
}

test "formatspanName encodes metadata" {
    const formatted = try formatSpanName(std.testing.allocator, "test.span", .{
        .root = true,
        .count = @as(u8, 42),
        .label = "batch",
    });
    defer std.testing.allocator.free(formatted);

    try std.testing.expectEqualStrings("test.span#_r=1,count=42,label=batch#", formatted);
}

test "formatspanName omits empty metadata" {
    const formatted = try formatSpanName(std.testing.allocator, "test.span", .{
        .root = false,
        .optional = @as(?u8, null),
    });
    defer std.testing.allocator.free(formatted);

    try std.testing.expectEqualStrings("test.span", formatted);
}

test "span_at encodes source with existing metadata in one section" {
    const source: std.lang.SourceLocation = .{
        .module = "test",
        .file = "src/test.zig",
        .fn_name = "example",
        .line = 42,
        .column = 7,
    };
    const metadata = .{ .root = true, .count = @as(i32, std.math.minInt(i32)), .phase = .decode };
    var bytes: [computeEncodedNameLen("test.span", @TypeOf(metadata)) + source_to_string(source).len + 7]u8 = undefined;
    var encoded: std.ArrayList(u8) = .initBuffer(&bytes);
    try appendEncodedNameAt(&encoded, .failing, source, "test.span", metadata);
    try std.testing.expectEqualStrings("test.span#_r=1,count=-2147483648,phase=decode,_src=src/test.zig:42:7#", encoded.items);

    // Exercise the public stack-buffer path and the copied-name lifetime too.
    var trace = span_at(source, "test.span", metadata);
    defer trace.end();
}

test "span_at retains source with empty or omitted metadata" {
    const source: std.lang.SourceLocation = .{
        .module = "test",
        .file = "test.zig",
        .fn_name = "example",
        .line = 1,
        .column = 2,
    };
    inline for (.{ .{}, @as(void, {}), .{ .root = false } }) |metadata| {
        var bytes: ["test.span#_src=test.zig:1:2#".len]u8 = undefined;
        var encoded: std.ArrayList(u8) = .initBuffer(&bytes);
        try appendEncodedNameAt(&encoded, .failing, source, "test.span", metadata);
        try std.testing.expectEqualStrings("test.span#_src=test.zig:1:2#", encoded.items);
        var trace = span_at(source, "test.span", metadata);
        trace.end();
    }
}

test "span_at_for encodes producer and consumer contexts as integers" {
    const source: std.lang.SourceLocation = .{
        .module = "test",
        .file = "test.zig",
        .fn_name = "example",
        .line = 1,
        .column = 2,
    };
    const producer: Context = .{ .namespace = .pjrt_library_call, .id = std.math.maxInt(i64) };
    const consumer: Context = .{ .namespace = .threadpool_event, .id = std.math.minInt(i64) };
    const metadata = .{ .iteration = @as(u64, std.math.maxInt(u64)) };
    var bytes: [computeEncodedNameLen("work", @TypeOf(metadata)) + source_to_string(source).len + 7 + max_context_fields_len]u8 = undefined;
    inline for (.{
        SpanContext{ .producer = producer },
        SpanContext{ .consumer = consumer },
        SpanContext{ .producer = producer, .consumer = consumer },
    }, .{
        "work#iteration=18446744073709551615,_src=test.zig:1:2,_pt=14,_p=9223372036854775807,_zml_flow=1#",
        "work#iteration=18446744073709551615,_src=test.zig:1:2,_ct=15,_c=-9223372036854775808,_zml_flow=1#",
        "work#iteration=18446744073709551615,_src=test.zig:1:2,_pt=14,_p=9223372036854775807,_ct=15,_c=-9223372036854775808,_zml_flow=1#",
    }) |context, expected| {
        var encoded: std.ArrayList(u8) = .initBuffer(&bytes);
        try appendEncodedNameAtFor(&encoded, .failing, source, "work", metadata, context);
        try std.testing.expectEqualStrings(expected, encoded.items);
        var trace = span_at_for(source, "work", metadata, context);
        trace.end();
    }
}

test "span_at_for supports empty metadata and absent contexts" {
    const source = @src();
    inline for (.{ .{}, @as(void, {}), .{ .root = false } }) |metadata| {
        var bytes: ["work#_src=#".len + source_to_string(source).len + max_context_fields_len]u8 = undefined;
        var encoded: std.ArrayList(u8) = .initBuffer(&bytes);
        try appendEncodedNameAtFor(&encoded, .failing, source, "work", metadata, .{});
        try std.testing.expectEqualStrings("work#_src=" ++ source_to_string(source) ++ "#", encoded.items);
        var trace = span_at_for(source, "work", metadata, .{});
        trace.end();
    }
}

test "contexts get distinct TraceMe activity IDs without requiring a session" {
    const first: Context = .init(.generic);
    const second: Context = .init(.generic);
    try std.testing.expect(first.id > 0);
    try std.testing.expect(second.id > 0);
    try std.testing.expect(first.id != second.id);
    var producer = span_at_for(@src(), "schedule", .{}, .{ .producer = first });
    producer.end();
    var consumer = span_at_for(@src(), "execute", .{}, .{ .consumer = first });
    consumer.end();
}
